const assertReplace = (s,needle,replacement,label) => {
 const occurrences=s.split(needle).length-1;
 if(occurrences!==1) throw Error(`[V3.8] ${label}: expected 1 anchor, found ${occurrences}. Original file preserved.`);
 return s.replace(needle,replacement);
};
// JSON-like keys containing apostrophes, backslashes etc may elude the regexp, so use
// a second exact key list generated by the patch package.
const covered = new Set(JSON.parse(read('scripts/v38-translatable-keys.json')));
function applyJsxTranslations(path, source) {
  const sf=ts.createSourceFile(path,source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
  const edits=[];
  function walk(node){
    if(ts.isJsxText(node)){
      const raw=source.slice(node.pos,node.end);
      const v=raw.trim().replace(/\s+/g,' ');
      if(covered.has(v)) {
        const lead=raw.match(/^\s*/)?.[0]??'';
        const tail=raw.match(/\s*$/)?.[0]??'';
        edits.push([node.pos,node.end,`${lead}{t(${JSON.stringify(v)})}${tail}`]);
      }
    }
    if(ts.isJsxAttribute(node) && !!node.initializer && ts.isStringLiteral(node.initializer) && ['title','aria-label','placeholder','alt','aria-description'].includes(node.name.text)){
      const v=node.initializer.text;
      if(covered.has(v)) edits.push([node.initializer.pos,node.initializer.end,`{t(${JSON.stringify(v)})}`]);
    }
    ts.forEachChild(node,walk);
  }
  walk(sf);
  for(const [start,end,replacement] of edits.sort((a,b)=>b[0]-a[0]))source=source.slice(0,start)+replacement+source.slice(end);
  console.log(`[V3.8] ${path}: ${edits.length} static translations`);
  return source;
}
